    assert(await page.locator('#saved-budget').innerText() === '₩1,200,000', 'Dedicated settings UI changes budget');
    assert(await page.locator('#available').innerText() === '₩640,000', 'Existing expenses preserved on save');
    await page.screenshot({ path: `${evidence}/settings.png`, fullPage: true });
