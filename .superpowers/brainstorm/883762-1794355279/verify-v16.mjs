    await page.screenshot({ path: `${evidence}/future-budgets.png`, fullPage: true });
    assert((await page.locator('#baseline-budget-chart').getAttribute('aria-label')).includes('₩720,000'), 'Baseline graph remains visible and unchanged');
    await page.getByText('할부 건별 내역과 기간별 금액', { exact: true }).click();
    await page.getByLabel('상세 조회 기간', { exact: true }).selectOption('5');
    assert((await page.locator('#commitment-breakdown').innerText()).includes('새 할부·결제 가정'), 'Each installment is listed separately');
    assert((await page.locator('#commitment-breakdown').innerText()).includes('₩100,000'), 'New installment persists into sixth period');
    await page.getByText('할부 건별 내역과 기간별 금액', { exact: true }).click();
    await page.getByRole('button', { name: '결제 예시 제거', exact: true }).click();
    assert(await page.locator('#simulation-result').isHidden(), 'Future projection hidden until simulator opened');
