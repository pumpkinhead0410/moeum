import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const { chromium } = createRequire('/home/juno/.cache/easydocs-verify/package.json')('playwright-core');
const phase = 'v6';
const session = fileURLToPath(new URL('.', import.meta.url));
const evidence = `${session}evidence/${phase}`;
mkdirSync(evidence, { recursive: true });
writeFileSync(`${evidence}/fonts.conf`, '<?xml version="1.0"?><!DOCTYPE fontconfig SYSTEM "fonts.dtd"><fontconfig><include ignore_missing="yes">/etc/fonts/fonts.conf</include><dir>/mnt/c/Windows/Fonts</dir><cachedir>/tmp/moeum-mockup-fontcache</cachedir></fontconfig>');
const browser = await chromium.launch({ executablePath: '/home/juno/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome', headless: true, args: ['--no-sandbox'], env: { ...process.env, FONTCONFIG_FILE: `${evidence}/fonts.conf` } });
const errors = [], steps = [], imageResponses = [];
const assert = (condition, label) => { steps.push({ label, pass: Boolean(condition) }); if (!condition) throw Error(label); };
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'ko-KR', timezoneId: 'Asia/Seoul' });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('response', r => { if (r.url().includes('sure-reference')) imageResponses.push({ status: r.status(), contentType: r.headers()['content-type'] }); if (r.status() >= 400) errors.push(`HTTP ${r.status()} ${new URL(r.url()).pathname}`); });
  const info = JSON.parse(readFileSync(`${session}state/server-info`, 'utf8'));
  await page.goto(info.url);
  await page.getByRole('heading', { name: '대시보드', exact: true }).waitFor();
  await page.getByText('Sure 기존 대시보드 참고', { exact: true }).click();
  const img = page.getByAltText('저장소에 포함된 Sure 기존 대시보드');
  await img.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('.history img').complete);
  const image = await img.evaluate(el => ({ complete: el.complete, width: el.naturalWidth, height: el.naturalHeight, source: el.src.startsWith('data:') ? 'embedded image/webp' : new URL(el.src).pathname }));
  await page.screenshot({ path: `${evidence}/reference.png`, fullPage: true });
  writeFileSync(`${evidence}/image.json`, JSON.stringify({ image, imageResponses }, null, 2));
  if (phase === 'before') { assert(image.width === 0, 'Broken reference image reproduced'); }
  else {
    assert(image.width > 0 && image.height > 0, 'Reference image decoded and displayed');
    assert(await page.getByText('11월 11일 거래 입력 완료', { exact: true }).count() === 2, 'Both initial input states preserved after companion connects');
    assert(!await page.getByRole('heading', { name: '순자산', exact: true }).isVisible(), 'Net worth hidden on daily landing view');
    assert(await page.getByRole('heading', { name: '이번 달 사용 가능한 생활비', exact: true }).isVisible(), 'Living budget visible on landing view');
    assert(await page.getByText('설정 목표', { exact: false }).count() === 0, 'Goal information removed');
    await page.getByRole('tab', { name: '자산·흐름' }).click();
    await page.getByRole('button', { name: '일', exact: true }).click();
    assert((await page.locator('#change').innerText()).includes('−₩60,000'), 'Day period selected');
    await page.getByRole('button', { name: '월', exact: true }).click();
    assert((await page.locator('#change').innerText()).includes('+₩800,000'), 'Month period selected');
    await page.getByRole('button', { name: '주', exact: true }).click();
    assert((await page.locator('#change').innerText()).includes('+₩140,000'), 'Week period selected');
    await page.getByLabel('입력 상태', { exact: true }).selectOption('empty');
    await page.getByRole('button', { name: '오늘 거래 없음을 확인' }).click();
    assert(await page.getByText('11월 11일 거래 없음 · 직접 확인 완료', { exact: true }).count() === 2, 'No-transaction confirmation updates both cards');
    assert(await page.getByRole('button', { name: '오늘 거래 없음을 확인' }).count() === 0, 'Confirmation action removed after opt-in');
    await page.getByLabel('입력 상태', { exact: true }).selectOption('missing');
    assert(await page.getByText('11월 10일·11일 입력 확인 없음', { exact: true }).count() === 2, 'Missing-input state displayed on both cards');
    await page.screenshot({ path: `${evidence}/missing-input.png`, fullPage: true });
    await page.getByLabel('입력 상태', { exact: true }).selectOption('recorded');
    await page.getByRole('tab', { name: '매일 확인' }).click();
    await page.getByText('남은 할부 일정', { exact: true }).click();
    await page.screenshot({ path: `${evidence}/daily.png`, fullPage: true });
    await page.getByRole('tab', { name: '자산·흐름' }).click();
    assert(await page.getByRole('heading', { name: '순자산', exact: true }).count() === 1, 'Only one net-worth card');
    assert(await page.getByRole('heading', { name: '기간 내 순자산 증감 구성', exact: true }).count() === 0, 'Duplicate breakdown removed');
    await page.getByText('부채 · ₩980,000', { exact: true }).click();
    assert(await page.getByText('할부 미납 원금 전체', { exact: true }).isVisible(), 'Existing balance-sheet section shows debt details');
    await page.getByText('Sure 기존 대시보드 참고', { exact: true }).click();
    await page.screenshot({ path: `${evidence}/desktop.png`, fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desktop has no horizontal overflow');
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px mobile has no horizontal overflow');
    await page.screenshot({ path: `${evidence}/mobile-assets.png`, fullPage: true });
    await page.getByRole('tab', { name: '매일 확인' }).click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile daily view has no horizontal overflow');
    await page.screenshot({ path: `${evidence}/mobile.png`, fullPage: true });
    await page.getByRole('tab', { name: '매일 확인' }).focus();
    await page.keyboard.press('ArrowRight');
    assert(await page.getByRole('tab', { name: '자산·흐름' }).getAttribute('aria-selected') === 'true', 'Keyboard tab navigation works');
    assert(errors.length === 0, 'No browser console, page, or HTTP errors');
  }
} finally {
  writeFileSync(`${evidence}/errors.json`, JSON.stringify(errors, null, 2));
  writeFileSync(`${evidence}/steps.json`, JSON.stringify(steps, null, 2));
  await browser.close();
}
console.log(JSON.stringify({ phase, steps, errors, evidence }, null, 2));
